// Writes sw-files.js: every file the game needs offline, and a hash of them all as the cache version.
// Run after changing any game file: npm run sw (npm run vendor runs it too).
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { createHash } from 'node:crypto';

const root = resolve(dirname(new URL(import.meta.url).pathname), '..');
const walk = dir => readdirSync(join(root, dir)).flatMap(name => {
  const p = `${dir}/${name}`;
  if (name.startsWith('.')) return [];
  return statSync(join(root, p)).isDirectory() ? walk(p) : [p];
});

const files = ['index.html', 'manifest.webmanifest', ...['css', 'js', 'vendor', 'fonts', 'icons'].flatMap(walk)].sort();
const hash = createHash('sha256');
for (const f of files) hash.update(f).update(readFileSync(join(root, f)));
const version = hash.digest('hex').slice(0, 12);

writeFileSync(join(root, 'sw-files.js'), `// Generated by scripts/sw-files.mjs — do not edit.\nself.SW_FILES = ${JSON.stringify({ version, files: ['./', ...files] }, null, 2)};\n`);
console.log(`sw-files.js: ${files.length} files, version ${version}`);
